// The token radar's model, radar-3: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol in the snapshot that can plausibly issue a token of its own: the
// whole watchlist (the floor, never a ceiling) plus every other rankable pre-token protocol below
// the floor. A protocol is rankable when the snapshot records no token for it (no market cap, no
// CoinGecko id, no symbol) and it is not one of the products the watchlist rule itself excludes:
// CEX, Bridge, Canonical Bridge, Liquid Staking, Liquid Restaking, Restaked BTC, a name ending in
// a version marker, or a name carrying the whole word wrapped, staked or staking. Those are wrapped,
// staked or bridged products of a token that already trades, not launches waiting to happen.
// Live-token protocols are kept apart and shown with the market's own values, never mixed into the
// ranked board.
//
// Implied value follows only from the snapshot's own figures, in one function per protocol:
//
//   multiple   = median market-cap / TVL of the LIVE-token protocols in the same category
//                (at least 3 of them; otherwise the global median across all live protocols),
//                clamped to [0.05, 1.00] — the market's own pricing of that kind of protocol
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = MATURITY_FLOOR + min(age_days, MATURITY_DAYS) / MATURITY_DAYS x MATURITY_RANGE
//                (age_days unknown: UNKNOWN_AGE_DAYS — how long it has run with no token)
//   breadth    = min(BREADTH_MAX_MULT, 1 + BREADTH_LOG_STEP x log2(max(chains, 1)))
//                — a diminishing-returns curve, not a line: the old linear factor
//                1 + 0.05 x min(chains - 1, 4) stopped at 5 chains, and 34 of the 198 ranked
//                protocols run on 5 or more chains (the widest on 45), so a sixth of the board
//                shared one breadth value and reach stopped counting. log2 keeps rewarding
//                reach while flattening, and the cap bounds the factor at 1.40.
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard
// recomputes each row from the same figures, so the page and board.json always agree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

